/**
 * Determines the EXPECTED enabled/disabled state of Add Resources modal
 * buttons (`zip`, `courses`, ...), independent of the button under test.
 *
 * The app disables resource types via `NEXT_PUBLIC_DISABLED_DATASETS`
 * (pipe-separated ids, default `'zip|courses'` — see `lib/config.ts`'s
 * `disabedDatasets()` and `lib/utils.ts`'s `disabledDatasetResourceTypes()`).
 * This is a NEXT_PUBLIC_ var, so it is inlined into the client bundle at BUILD
 * time; the value the running app actually enforces is whatever Next.js
 * resolved when `pnpm build` ran, not whatever `e2e/.env.local` happens to say
 * (that file is Playwright's own config, read by `e2e/playwright.config.ts`,
 * and has no bearing on the Next.js build).
 *
 * Two ways that build-time value can reach the browser:
 *
 *   1. Runtime templating — `env.js`, generated by `entrypoint.sh` in a real
 *      deployment, sets `window.__ENV__` before the app boots; `getEnv()`
 *      prefers this over the build-time value when non-empty. A bare
 *      `pnpm build && pnpm start` (as used for local E2E runs) never runs
 *      `entrypoint.sh`, so `window.__ENV__` is `{}` — but a containerized
 *      target might set it, so this is checked first and wins if present.
 *   2. Next.js's own build-time env-file precedence for `NODE_ENV=production`
 *      (docs: https://nextjs.org/docs/app/api-reference/config/next-config-js/env):
 *        .env.production.local > .env.local > .env.production > .env
 *      all read from the REPO ROOT (next to package.json) — NOT `e2e/.env*`.
 *      Whichever of these files is present AND sets a non-empty
 *      `NEXT_PUBLIC_DISABLED_DATASETS` first, by that precedence, wins.
 *
 * If nothing sets it, the code's own hardcoded default (`'zip|courses'`,
 * mirrored in `CODE_DEFAULT_DISABLED` below) is what `lib/config.ts` falls
 * back to — that IS the correctly-determined value, not an unknown. This
 * helper only throws when it cannot even determine that much (e.g. the repo
 * root doesn't look like this repo at all), never as a way to signal
 * "assume disabled" — a caller must always get a real, reasoned answer.
 */

import fs from 'fs';
import path from 'path';
import type { Page } from '@playwright/test';

/**
 * Resource-type ids the Add Resources modal can gate. Mirrors the id list in
 * `@iblai/web-containers`'s resource-types definition (verified against the
 * live `.yalc/@iblai/web-containers/dist/index.esm.js` on 2026-09-28). Page
 * objects/utils don't import SDK source, so this is a literal — keep in sync
 * if the SDK ever renames an id.
 */
export const ALL_DATASET_RESOURCE_IDS = [
  'powerpoint',
  'onedrive',
  'google-drive',
  'dropbox',
  'youtube',
  'url',
  'pdf',
  'docx',
  'excel',
  'csv',
  'github',
  'text',
  'markdown',
  'audio',
  'video',
  'image',
  'web-crawler',
  'zip',
  'courses',
] as const;

export type DatasetResourceId = (typeof ALL_DATASET_RESOURCE_IDS)[number];

/** Mirrors lib/config.ts's `disabedDatasets()` hardcoded fallback exactly. */
const CODE_DEFAULT_DISABLED = 'zip|courses';

/**
 * Next.js env-file precedence for a production build, highest first. Read
 * from the repo root — two levels up from `e2e/utils/` — never from
 * `e2e/.env*` (Playwright's own config, unrelated to the Next.js build).
 */
const ENV_FILES_BY_PRECEDENCE = [
  '.env.production.local',
  '.env.local',
  '.env.production',
  '.env',
];

const REPO_ROOT = path.resolve(__dirname, '../..');

function parseEnvFile(filePath: string): Record<string, string> {
  const out: Record<string, string> = {};
  const content = fs.readFileSync(filePath, 'utf-8');
  for (const rawLine of content.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

/**
 * Reads `NEXT_PUBLIC_DISABLED_DATASETS` the way THIS worktree's Next.js build
 * resolved it, by walking the same env-file precedence Next.js uses. Sanity-
 * checks that `REPO_ROOT` actually looks like this repo before trusting an
 * "unset" result — a broken path resolution must fail loudly rather than
 * silently reporting "everything enabled".
 */
function readDisabledIdsFromEnvFiles(): string[] {
  const sentinel = path.join(REPO_ROOT, 'lib', 'config.ts');
  if (!fs.existsSync(sentinel)) {
    throw new Error(
      `[dataset-resource-gating] REPO_ROOT resolved to "${REPO_ROOT}", which ` +
        'does not contain lib/config.ts — path resolution is broken. Refusing ' +
        'to guess the expected disabled-resource-types value.',
    );
  }

  for (const file of ENV_FILES_BY_PRECEDENCE) {
    const filePath = path.join(REPO_ROOT, file);
    if (!fs.existsSync(filePath)) continue;
    const parsed = parseEnvFile(filePath);
    const raw = parsed.NEXT_PUBLIC_DISABLED_DATASETS;
    if (raw !== undefined && raw !== '') {
      return raw.split('|').filter(Boolean);
    }
  }

  // No env file sets it anywhere in the precedence chain — this IS the
  // determined value: lib/config.ts's own hardcoded default applies.
  return CODE_DEFAULT_DISABLED.split('|').filter(Boolean);
}

/**
 * Determines the expected disabled-resource-type ids for the currently
 * running app build — NEVER by reading the button under test. See the
 * module doc comment for the full precedence.
 */
export async function getExpectedDisabledResourceIds(
  page: Page,
): Promise<string[]> {
  const runtimeValue = await page.evaluate(() => {
    const env = (window as { __ENV__?: Record<string, string> }).__ENV__;
    return env?.NEXT_PUBLIC_DISABLED_DATASETS;
  });
  if (typeof runtimeValue === 'string' && runtimeValue !== '') {
    return runtimeValue.split('|').filter(Boolean);
  }
  return readDisabledIdsFromEnvFiles();
}

/**
 * True when `resourceId` is expected to be ENABLED in the Add Resources modal
 * for the currently running app build.
 */
export async function expectedResourceEnabled(
  page: Page,
  resourceId: DatasetResourceId,
): Promise<boolean> {
  const disabled = await getExpectedDisabledResourceIds(page);
  return !disabled.includes(resourceId);
}
